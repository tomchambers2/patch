// Generate vendor/xtermAssets.ts — xterm.js, its fit addon and its stylesheet
// as string constants, for the host terminal's WebView (spec/15 § Host files
// and terminal).
//
// The terminal page is built in JS and handed to the WebView as an inline HTML
// string. Loading xterm.js from a CDN instead would make a working terminal
// depend on a third party being up and reachable from the phone, and Metro has
// no loader that turns a .js file under node_modules into a string. So the
// sources are baked into a module at a pinned version, and
// `__tests__/xtermAssets.test.ts` fails when this file no longer matches what
// the installed packages would produce — bump the devDependencies, re-run:
//
//   node scripts/gen-xterm-assets.mjs
//
// NO FALLBACK: a source that contains `</script` would end the inline <script>
// early and leave a page that half-loads; the generator refuses it outright.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_FILE = resolve(APP_DIR, 'vendor/xtermAssets.ts');

function pkg(name) {
  const dir = resolve(APP_DIR, 'node_modules', name);
  return { dir, version: JSON.parse(readFileSync(resolve(dir, 'package.json'), 'utf8')).version };
}

/** The file's full text, from the installed packages. */
export function render() {
  const xterm = pkg('@xterm/xterm');
  const fit = pkg('@xterm/addon-fit');
  const sources = {
    XTERM_JS: readFileSync(resolve(xterm.dir, 'lib/xterm.js'), 'utf8'),
    XTERM_CSS: readFileSync(resolve(xterm.dir, 'css/xterm.css'), 'utf8'),
    FIT_ADDON_JS: readFileSync(resolve(fit.dir, 'lib/addon-fit.js'), 'utf8'),
  };
  for (const [name, text] of Object.entries(sources)) {
    if (/<\/script/i.test(text) || /<\/style/i.test(text)) {
      throw new Error(`gen-xterm-assets: ${name} contains a closing tag and cannot be inlined`);
    }
  }
  const lines = [
    '// GENERATED by scripts/gen-xterm-assets.mjs — do not edit by hand.',
    `// @xterm/xterm ${xterm.version} and @xterm/addon-fit ${fit.version} (MIT licence,`,
    '// Copyright (c) The xterm.js authors), inlined for the terminal WebView.',
    '/* eslint-disable */',
    '',
    `export const XTERM_VERSION = ${JSON.stringify(xterm.version)};`,
    `export const FIT_ADDON_VERSION = ${JSON.stringify(fit.version)};`,
  ];
  for (const [name, text] of Object.entries(sources)) {
    lines.push(`export const ${name} = ${JSON.stringify(text)};`);
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT_FILE, render());
  console.log(`wrote ${OUT_FILE}`);
}
